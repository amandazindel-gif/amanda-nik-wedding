#!/usr/bin/env node
/* Static site build. No dependencies: Node reads the data module, renders every
   page to dist/<route>/index.html, and copies assets, styles and scripts.

   Env:
     BASE_URL   path the site is served from (default "/"). For a project
                GitHub Pages site use "/<repo>/".
     CNAME      custom domain to write into dist/CNAME.
*/

import { cp, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { wedding } from "./src/data/wedding-data.js";
import { setBase } from "./src/components/util.js";
import { layout } from "./src/components/layout.js";

import home from "./src/pages/home.js";
import story from "./src/pages/story.js";
import schedule from "./src/pages/schedule.js";
import travel from "./src/pages/travel.js";
import stay from "./src/pages/stay.js";
import explore from "./src/pages/explore.js";
import wear from "./src/pages/wear.js";
import guests from "./src/pages/guests.js";
import faq from "./src/pages/faq.js";
import rsvp from "./src/pages/rsvp.js";

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, "dist");

const rawBase = process.env.BASE_URL || "/";
const base = (rawBase.startsWith("/") ? rawBase : "/" + rawBase).replace(/\/*$/, "/");
setBase(base);

const PAGES = [home, story, schedule, travel, stay, explore, wear, guests, faq, rsvp];

async function writePage(page) {
  const html = layout(page, { base, daisyChips: wedding.daisyChips });
  const dir = page.route === "/" ? dist : join(dist, page.route.replace(/^\/|\/$/g, ""));
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, "index.html"), html, "utf8");
  return page;
}

/* Daisy's client-side fallback needs the FAQ copy and the proxy URL. */
async function writeDaisyData() {
  const body = `/* Generated by build.mjs from src/data/wedding-data.js. Do not edit. */
export const DAISY = ${JSON.stringify(
    {
      endpoint: wedding.daisyEndpoint || "",
      faqs: wedding.faqs.map((f) => ({ q: f.q, a: f.a }))
    },
    null,
    2
  )};
`;
  await writeFile(join(dist, "scripts", "daisy-data.js"), body, "utf8");
}

async function main() {
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });

  // Static files served as-is.
  await cp(join(root, "public"), dist, { recursive: true });
  await cp(join(root, "src", "styles"), join(dist, "styles"), { recursive: true });
  await cp(join(root, "src", "scripts"), join(dist, "scripts"), { recursive: true });
  await writeDaisyData();

  const written = [];
  for (const page of PAGES) written.push(await writePage(page(wedding)));

  // GitHub Pages: don't run Jekyll over the output.
  await writeFile(join(dist, ".nojekyll"), "", "utf8");

  // A 404 that still carries the nav, so a bad link isn't a dead end.
  const notFound = layout(
    {
      title: "Page not found · Amanda & Nik",
      desc: "That page doesn't exist.",
      current: "",
      body: `
<main>
  <section class="section section--last" style="padding-top:80px">
    <div class="page-head">
      <p class="eyebrow">404</p>
      <h1>Daisy ate this page</h1>
      <p>It isn't here. Try the schedule, the travel notes, or head back to the start.</p>
      <p style="margin-top:22px"><a class="btn btn--primary" href="${base}">Back to the beginning</a></p>
    </div>
  </section>
</main>`
    },
    { base, daisyChips: wedding.daisyChips }
  );
  await writeFile(join(dist, "404.html"), notFound, "utf8");

  const origin = process.env.SITE_ORIGIN || "";
  if (origin) {
    const urls = written
      .map((p) => `  <url><loc>${origin.replace(/\/$/, "")}${base}${p.route.replace(/^\//, "")}</loc></url>`)
      .join("\n");
    await writeFile(
      join(dist, "sitemap.xml"),
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
      "utf8"
    );
  }

  if (process.env.CNAME) await writeFile(join(dist, "CNAME"), process.env.CNAME.trim() + "\n", "utf8");

  const files = await readdir(dist);
  console.log(`Built ${written.length} pages into dist/ (base "${base}")`);
  console.log("  " + files.sort().join("  "));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
